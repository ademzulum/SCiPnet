// Writes supabase/seed.sql from the entries in src/data/*.ts (the state before
// the move to the database). Run: node scripts/seed.mjs
import { createServer } from 'vite';
import { writeFileSync } from 'node:fs';

const vite = await createServer({ server: { middlewareMode: true }, appType: 'custom', logLevel: 'error' });
const load = (f) => vite.ssrLoadModule(`/src/data/${f}.ts`);
const [{ SCP }, { PERSONNEL }, { REPORTS }, { MTFS }, { GOIS }] = await Promise.all(
  ['scp', 'personnel', 'reports', 'mtf', 'gois'].map(load),
);
await vite.close();

// insignias are image imports; the database keeps the file name only
const mtfs = MTFS.map((m) => ({ ...m, insignia: m.insignia.split('/').pop().replace(/\?.*$/, '') }));

const q = (s) => `'${s.replace(/'/g, "''")}'`;
const rows = [
  ['scp', SCP],
  ['personnel', PERSONNEL],
  ['report', REPORTS],
  ['mtf', mtfs],
  ['goi', GOIS],
].flatMap(([kind, list]) => list.map((e, i) => `(${q(kind)}, ${q(e.id)}, ${i}, ${q(JSON.stringify(e))}::jsonb)`));

writeFileSync(
  'supabase/seed.sql',
  `-- Generated by scripts/seed.mjs: the entries that used to live in src/data.
-- Run after schema.sql. Existing rows with the same id are overwritten.
insert into public.entries (kind, id, position, data) values
${rows.join(',\n')}
on conflict (kind, id) do update set position = excluded.position, data = excluded.data;
`,
);
console.log(`${rows.length} entries`);
