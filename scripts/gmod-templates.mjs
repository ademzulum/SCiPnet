// Writes ../SCiPnet PDA/scipnet/lua/scipnet/cl_templates.lua from src/data/reports.ts,
// so the in-game editor offers the same report templates as the site.
// Run after changing a template: node scripts/gmod-templates.mjs
import { writeFileSync } from 'node:fs';
import { TEMPLATES } from '../src/data/reports.ts';

const str = (s) => JSON.stringify(s ?? '');
const parts = (list) => '{ ' + list.map(([n, h]) => `{ ${str(n)}, ${str(h)} }`).join(', ') + ' }';
const std = (o) => '{ ' + Object.entries(o ?? {}).map(([k, v]) => `${k} = ${str(v)}`).join(', ') + ' }';
const rows = Object.entries(TEMPLATES).map(
  ([k, t]) =>
    `\t{ key = ${str(k)}, label = ${str(t.label)}, use = ${str(t.use)}, example = ${str(t.example)},\n\t\tfacts = ${parts(t.facts)},\n\t\tsections = ${parts(t.sections)},\n\t\tstd = ${std(t.std)} },`,
);
writeFileSync(
  new URL('../../SCiPnet%20PDA/scipnet/lua/scipnet/cl_templates.lua', import.meta.url),
  `-- Generated by scripts/gmod-templates.mjs from src/data/reports.ts. Do not edit.\nSCIPNET.ReportTemplates = {\n${rows.join('\n')}\n}\n`,
);
console.log(`${rows.length} templates written`);
