// Writes ../SCiPnet PDA/scipnet/lua/scipnet/sh_classes.lua from src/data/acsClasses.ts,
// so the Garry's Mod addon reads the ACS classes from the same source as the
// site. Run after changing a class: node scripts/gmod-classes.mjs
import { writeFileSync } from 'node:fs';
import { ALL_CLASSES, CONTAINMENT, SECONDARY } from '../src/data/acsClasses.ts';

const str = (s) => JSON.stringify(s);
// group: containment, secondary (official) or esoteric, for the editor's class picker
const group = (c) => (CONTAINMENT.includes(c) ? 'containment' : SECONDARY.includes(c) ? 'secondary' : 'esoteric');
const rows = ALL_CLASSES.map(
  (c) => `\t{ name = ${str(c.name)}, icon = ${str(c.icon)}, color = ${str(c.color)}, info = ${str(c.info)}, group = ${str(group(c))} },`,
);
const lua = `-- Generated by scripts/gmod-classes.mjs from src/data/acsClasses.ts. Do not edit.
SCIPNET.Classes = {
${rows.join('\n')}
}
`;
writeFileSync(new URL('../../SCiPnet%20PDA/scipnet/lua/scipnet/sh_classes.lua', import.meta.url), lua);
console.log(`${ALL_CLASSES.length} classes written`);
