// Writes ../SCiPnet PDA/scipnet/lua/scipnet/cl_globeland.lua and cl_globeborders.lua: the coastlines and country
// borders of world-atlas (the website's globe, src/scipnet/Globe.tsx) as flat
// lon/lat lists, for the wireframe globe in the GMod overview.
//   node scripts/gmod-globe.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { feature, mesh } from 'topojson-client';

const topo = JSON.parse(readFileSync(new URL('../node_modules/world-atlas/countries-110m.json', import.meta.url), 'utf8'));
const land = feature(topo, topo.objects.land);
const borders = mesh(topo, topo.objects.countries, (a, b) => a !== b);

const rings = [];
for (const f of land.features) {
  const g = f.geometry;
  const polys = g.type === 'Polygon' ? [g.coordinates] : g.coordinates;
  for (const poly of polys) for (const ring of poly) rings.push(ring);
}
const lines = borders.type === 'MultiLineString' ? borders.coordinates : [borders.coordinates];

const n = (v) => +v.toFixed(1);
const out = (list) =>
  list
    .filter((r) => r.length > 1)
    .map((r) => '\t{' + r.flatMap(([lon, lat]) => [n(lon), n(lat)]).join(',') + '},')
    .join('\n');

// one file each, so no single file grows past 64 KB
const write = (file, name, list) =>
  writeFileSync(
    new URL('../../SCiPnet%20PDA/scipnet/lua/scipnet/' + file, import.meta.url),
    `-- Generated by scripts/gmod-globe.mjs from world-atlas (countries-110m); do not edit.
-- Every list is lon, lat, lon, lat, ...
SCIPNET.${name} = {
${out(list)}
}
`,
  );
write('cl_globeland.lua', 'GlobeLand', rings);
write('cl_globeborders.lua', 'GlobeBorders', lines);
console.log(rings.length, 'rings,', lines.length, 'border lines');
